-- ============================================================
-- CORTEX SEARCH SERVICE: Policy Document Search
-- ============================================================

-- First, chunk policy documents into POLICY_DOCUMENT_CHUNKS
INSERT INTO ANALYTICS.POLICY_DOCUMENT_CHUNKS (CHUNK_ID, DOC_ID, TITLE, CATEGORY, JURISDICTION, CHUNK_TEXT, CHUNK_INDEX, STATUS)
SELECT
    'CHK_' || DOC_ID || '_' || 1,
    DOC_ID, TITLE, CATEGORY, JURISDICTION, FULL_TEXT, 1, 'ACTIVE'
FROM RAW.POLICY_DOCUMENTS
WHERE STATUS = 'APPROVED';

CREATE OR REPLACE CORTEX SEARCH SERVICE ANALYTICS.POLICY_SEARCH_SERVICE
    ON CHUNK_TEXT
    ATTRIBUTES TITLE, CATEGORY, JURISDICTION
    WAREHOUSE = COMPUTE_WH
    TARGET_LAG = '1 hour'
AS (
    SELECT CHUNK_TEXT, TITLE, CATEGORY, JURISDICTION
    FROM ANALYTICS.POLICY_DOCUMENT_CHUNKS
    WHERE STATUS = 'ACTIVE'
);

