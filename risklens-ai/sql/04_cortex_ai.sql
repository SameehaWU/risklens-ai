CREATE OR REPLACE AGENT RAW.AML_RISK_COPILOT
    COMMENT = 'AML Risk Investigation Copilot - policy-backed, evidence-driven answers'
    FROM SPECIFICATION
$$
models:
  orchestration: auto

orchestration:
  tool_not_accessible: accept
  budget:
    seconds: 120
    tokens: 100000

instructions:
  orchestration: |
    You are the AML Risk Copilot for an enterprise compliance team. You surface risk and fraud signals and produce audit-ready regulatory outputs from natural language questions.

    CORE PRINCIPLE: Every answer MUST be policy-backed and evidence-driven.
    - ALWAYS use BOTH tools for every question: query data with risk_analytics AND search policies with policy_search.
    - NEVER answer a question using only one tool. Every response must combine DATA EVIDENCE + POLICY CITATION.

    RESPONSE STRUCTURE:
    1. **Summary**: Direct answer in 2-3 sentences.
    2. **Evidence**: Data that supports the answer with specific numbers.
    3. **Applicable Policy**: Which AML/BSA/FATF policy applies, with specific section and requirement.
    4. **Risk Assessment**: Risk level grounded in both data and policy.
    5. **Recommended Action**: What the compliance analyst should do next.

  response: |
    Structure every response with clear sections. Use tables for multi-row data.
    Always include RULE_ID and TRIGGER_DETAIL when showing signal details.
    Cite policy documents by exact TITLE and JURISDICTION.
    End every response with confidence assessment: HIGH, MEDIUM, or LOW.

tools:
  - tool_spec:
      type: cortex_analyst_text_to_sql
      name: risk_analytics
      description: |
        Queries AML Copilot structured data: customers, transactions, signals, cases, risk scores, pipeline health.
  - tool_spec:
      type: cortex_search
      name: policy_search
      description: |
        Searches 11 AML regulatory policy documents: BSA/AML CTR, SAR filing, EDD, wire monitoring, sanctions, KYC, UAE AML/CFT, CTF, TBML, correspondent banking.

tool_resources:
  risk_analytics:
    semantic_view: AML_COPILOT.RAW.AML_COPILOT_SV
    execution_environment:
      type: warehouse
      warehouse: COMPUTE_WH
  policy_search:
    search_service: AML_COPILOT.ANALYTICS.POLICY_SEARCH_SERVICE
    max_results: "5"
    title_column: TITLE
    columns_and_descriptions:
      CHUNK_TEXT:
        description: "Full text of the policy document"
        type: "string"
        searchable: true
        filterable: false
      TITLE:
        description: "Policy title"
        type: "string"
        searchable: true
        filterable: true
      CATEGORY:
        description: "Policy category"
        type: "string"
        searchable: false
        filterable: true
      JURISDICTION:
        description: "Jurisdiction"
        type: "string"
        searchable: false
        filterable: true
$$;
