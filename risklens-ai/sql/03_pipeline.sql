CREATE OR REPLACE TASK PIPELINE.DETECT_AML_SIGNALS
    WAREHOUSE = COMPUTE_WH
    SCHEDULE = '5 MINUTE'
    WHEN SYSTEM$STREAM_HAS_DATA('AML_COPILOT.PIPELINE.STREAM_NEW_TRANSACTIONS')
AS CALL PIPELINE.SP_DETECT_AML_SIGNALS();

CREATE OR REPLACE TASK PIPELINE.RUN_DATA_QUALITY_CHECKS
    WAREHOUSE = COMPUTE_WH
    SCHEDULE = '15 MINUTE'
