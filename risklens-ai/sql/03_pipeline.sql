-- ============================================================
-- STREAM: Track new transactions for incremental detection
-- ============================================================

CREATE OR REPLACE STREAM PIPELINE.STREAM_NEW_TRANSACTIONS
ON TABLE RAW.TRANSACTIONS
APPEND_ONLY = TRUE;

-- ============================================================
-- STORED PROCEDURE: Signal Detection (6 rules)
-- ============================================================
-- NOTE: Full procedure is ~300 lines of SQL. Key rules:
-- RULE_STRUCT_001: 3+ cash txns <$10K summing >$10K in 24h (Structuring)
-- RULE_RAPID_001: Inbound wire >$50K, outbound >80% within 48h (Rapid Movement)
-- RULE_VELOC_001: Txn count >3x 30-day daily average (Velocity Spike)
-- RULE_GEO_001: Txn to HIGH-risk country with no prior history (Unusual Geography)
-- RULE_DORM_001: Txn after 90+ days inactivity (Dormant Activation)
-- RULE_BENEF_001: >5 new beneficiaries in 7 days (Beneficiary Burst)
-- The full DDL is deployed in the Snowflake account. See sp_detect_aml_signals.sql for details.

-- ============================================================
-- STORED PROCEDURE: Data Quality Checks
