-- ============================================================
-- PIPELINE SCHEMA: Operational Tables
-- ============================================================

CREATE OR REPLACE TABLE PIPELINE.SIGNAL_DETECTION_RUNS (
    RUN_ID VARCHAR(30) PRIMARY KEY,
    START_TIME TIMESTAMP_NTZ,
    END_TIME TIMESTAMP_NTZ,
    STATUS VARCHAR(20),
    RECORDS_PROCESSED NUMBER(10,0) DEFAULT 0,
