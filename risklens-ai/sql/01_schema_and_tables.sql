    REVIEWED_AT TIMESTAMP_NTZ,
    REVIEW_NOTES VARCHAR(500)
);

-- ============================================================
-- ANALYTICS SCHEMA: Views
-- ============================================================

CREATE OR REPLACE VIEW ANALYTICS.V_LATEST_DATA_QUALITY AS
SELECT CHECK_NAME, TABLE_NAME, STATUS, PASS_RATE, OVERALL_PASS_RATE
FROM PIPELINE.DATA_QUALITY_RESULTS
QUALIFY ROW_NUMBER() OVER (PARTITION BY CHECK_NAME ORDER BY RUN_TIMESTAMP DESC) = 1;

