    EVENT_SOURCE VARCHAR(100),
    ENTITY_TYPE VARCHAR(50),
    ENTITY_ID VARCHAR(50),
    DETAIL VARCHAR(2000),
    USER_ID VARCHAR(50),
    LOGGED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
