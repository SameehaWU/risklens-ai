CREATE OR REPLACE TABLE PIPELINE.POLICY_DOCUMENTS_STAGED (
    DOC_ID VARCHAR(20) PRIMARY KEY,
    TITLE VARCHAR(200),
    CATEGORY VARCHAR(50),
