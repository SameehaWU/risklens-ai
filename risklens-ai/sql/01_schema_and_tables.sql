    ORIGIN_COUNTRY VARCHAR(3),
    DESTINATION_COUNTRY VARCHAR(3),
    BENEFICIARY_ID VARCHAR(20),
    IS_SUSPICIOUS BOOLEAN DEFAULT FALSE,
    TRANSACTION_TIMESTAMP TIMESTAMP_NTZ,
