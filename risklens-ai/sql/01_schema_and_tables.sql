CREATE OR REPLACE TABLE PIPELINE.DATA_QUALITY_RESULTS (
    CHECK_ID NUMBER AUTOINCREMENT PRIMARY KEY,
    RUN_TIMESTAMP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CHECK_NAME VARCHAR(100),
    TABLE_NAME VARCHAR(100),
    STATUS VARCHAR(10),
    PASS_RATE NUMBER(7,4),
    RECORDS_CHECKED NUMBER(10,0),
    RECORDS_FAILED NUMBER(10,0),
    OVERALL_PASS_RATE NUMBER(7,4)
);

CREATE OR REPLACE TABLE PIPELINE.GENERATED_REPORTS (
    REPORT_ID VARCHAR(50) PRIMARY KEY,
    CASE_ID VARCHAR(20),
    REPORT_TYPE VARCHAR(30),
